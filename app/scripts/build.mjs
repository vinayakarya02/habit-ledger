// Production build: assembles dist/ from the static sources, stamps the git commit into the bundle,
// adds hosting config, and fails if any referenced file or import is missing or a view fails to render.
// Usage: node scripts/build.mjs

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const fail = (msg) => { console.error(`BUILD FAILED: ${msg}`); process.exit(1); };

function git(cmd) {
  try { return execSync(`git ${cmd}`, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { return null; }
}

// 1. Clean and copy sources.
rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
cpSync(join(ROOT, 'index.html'), join(DIST, 'index.html'));
cpSync(join(ROOT, 'styles'), join(DIST, 'styles'), { recursive: true });
cpSync(join(ROOT, 'src'), join(DIST, 'src'), { recursive: true, filter: (p) => !p.endsWith('.md') });

// 2. Stamp the commit the bundle was built from.
const sha = git('rev-parse --short=12 HEAD');
const dirty = sha ? git('status --porcelain -- .') : null;
const commit = sha ? `${sha}${dirty ? '-dirty' : ''}` : 'unversioned';
const builtAt = new Date().toISOString();
writeFileSync(join(DIST, 'src', 'version.js'), `// Generated by scripts/build.mjs\nexport const VERSION = ${JSON.stringify({ commit, builtAt })};\n`);
writeFileSync(join(DIST, 'version.json'), `${JSON.stringify({ commit, builtAt }, null, 2)}\n`);

// 3. Hosting config: security headers. connect-src 'self' means the page cannot send imported data anywhere.
writeFileSync(join(DIST, 'vercel.json'), `${JSON.stringify({
  headers: [{
    source: '/(.*)',
    headers: [
      { key: 'Content-Security-Policy', value: "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; img-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'" },
      { key: 'X-Content-Type-Options', value: 'nosniff' },
      { key: 'Referrer-Policy', value: 'no-referrer' },
      { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
      { key: 'Cache-Control', value: 'no-cache' },
    ],
  }],
}, null, 2)}\n`);

// 4. Keep the Vercel project link (if this checkout has one) so `vercel deploy` from dist/ updates the same project.
if (existsSync(join(ROOT, '.vercel', 'project.json'))) cpSync(join(ROOT, '.vercel'), join(DIST, '.vercel'), { recursive: true });

// 5. Verify every file referenced by index.html exists.
const html = readFileSync(join(DIST, 'index.html'), 'utf8');
for (const [, ref] of html.matchAll(/(?:href|src)="([^"]+)"/g)) {
  if (/^https?:/.test(ref)) continue;
  if (!existsSync(join(DIST, ref))) fail(`index.html references missing file ${ref}`);
}

// 6. Verify every relative import in the bundle resolves.
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : p.endsWith('.js') && files.push(p); } })(join(DIST, 'src'));
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const [, spec] of src.matchAll(/(?:import|export)[^'"]*?from\s*['"](\.{1,2}\/[^'"]+)['"]/g)) {
    if (!existsSync(resolve(dirname(f), spec))) fail(`${relative(DIST, f)} imports missing module ${spec}`);
  }
}

// 7. Import the bundled modules and render every view for each sample trader.
const store = await import(pathToFileURL(join(DIST, 'src', 'store.js')).href);
const views = ['overview', 'habits', 'inspect', 'trades', 'guardrails', 'compare', 'import', 'lab', 'method'];
const mods = {};
for (const v of views) mods[v] = await import(pathToFileURL(join(DIST, 'src', 'views', `${v}.js`)).href);
let renders = 0;
for (const id of ['aarav', 'meera', 'kabir']) {
  const state = store.reduce(store.initialState(), { type: 'selectDataset', id });
  for (const v of views) {
    const out = mods[v].render({ ...state, view: v });
    if (typeof out !== 'string' || !out.length) fail(`view ${v} rendered nothing for ${id}`);
    renders++;
  }
}

const size = files.reduce((s, f) => s + statSync(f).size, 0);
console.log(`Built dist/ from commit ${commit}: ${files.length} modules (${(size / 1024).toFixed(0)} KB JS), ${renders} view renders OK.`);
